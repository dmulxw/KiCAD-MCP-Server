#!/usr/bin/env node
/**
 * Rewrite the board's mounting holes to match the library footprint they claim.
 *
 * `add_mounting_hole` synthesizes a footprint and then labels it
 * `MountingHole:MountingHole_2.7mm`, but it builds none of that library
 * footprint's content: no courtyard circle, no Cmts.User circle, no F.Fab
 * `${REFERENCE}` text, no `exclude_from_pos_files`/`exclude_from_bom`
 * attributes, and a pad layer set of `"*.Mask"` where the library uses
 * `"*.Cu" "*.Mask"`. The board therefore carries four footprints that say they
 * are a library part and are not, which DRC reports as:
 *
 *   [lib_footprint_mismatch] Footprint 'MountingHole_2.7mm' does not match
 *   copy in library 'MountingHole'.
 *
 * Two further problems fall out of the same construction:
 *
 *  - The synthesized pad default is `diameter + 1mm`, so a 2.7mm hole gets a
 *    3.7mm pad. An NPTH paints no copper, so the extra millimetre is purely a
 *    mask aperture -- 0.5mm of bare laminate around every hole, which bridged
 *    the ROW11 track at 1.83mm from MH4's centre (aperture reaches 1.85mm).
 *    The library sets size == drill and leaves no such ring.
 *  - With no courtyard, `check_courtyard_overlaps` falls back to a
 *    text-inclusive bounding box and reports the holes as colliding with their
 *    neighbours.
 *
 * This restores the library definition verbatim, keeping only the
 * instance-specific data the library cannot carry: the UUIDs, the position,
 * and the reference designator.
 *
 *   node projects/touch-panel/scripts/normalize-mounting-holes.mjs [board]
 */

import { readFileSync, writeFileSync, renameSync, unlinkSync, existsSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const DEFAULT_BOARD = join(HERE, "..", "touch-panel.kicad_pcb");

/** Library prefix whose footprints get restored. */
const PREFIX = "MountingHole:";

/** Library description, reproduced so the block reads like the library's. */
const DESCR =
  "Mounting Hole 2.7mm, no annular, generated by kicad-footprint-generator mountinghole.py";

const EFFECTS = `(effects
\t\t\t\t(font
\t\t\t\t\t(size 1 1)
\t\t\t\t\t(thickness 0.15)
\t\t\t\t)
\t\t\t)`;

/** Pull one `(property "Name" ...)`'s uuid out of an existing block. */
function propertyUuid(block, name) {
  const re = new RegExp(
    `\\(property\\s+"${name}"[\\s\\S]*?\\(uuid\\s+"([^"]+)"\\)`,
  );
  const m = block.match(re);
  return m ? m[1] : null;
}

function scalar(block, re) {
  const m = block.match(re);
  return m ? m[1] : null;
}

/**
 * Build the library-equivalent block for one mounting hole.
 *
 * Indentation matches the surrounding board (`\t` for the footprint, `\t\t`
 * for its children) so restoring a hole does not show up as a whole-block
 * diff. KiCad re-serializes on save, so this is cosmetic, but it keeps the
 * file readable in the meantime.
 */
function libraryBlock(keep) {
  const refProp = keep.refUuid ? `\n\t\t\t(uuid "${keep.refUuid}")` : "";
  const padUuid = keep.padUuid ? `\n\t\t\t(uuid "${keep.padUuid}")` : "";

  return `\t(footprint "${PREFIX}MountingHole_2.7mm"
\t\t(layer "F.Cu")
\t\t(uuid "${keep.fpUuid}")
\t\t(at ${keep.at})
\t\t(descr "${DESCR}")
\t\t(tags "mountinghole")
\t\t(attr exclude_from_pos_files exclude_from_bom)
\t\t(property "Reference" "${keep.ref}"
\t\t\t(at 0 -3.65 0)
\t\t\t(layer "F.SilkS")${refProp}
\t\t\t${EFFECTS}
\t\t)
\t\t(property "Value" "MountingHole_2.7mm"
\t\t\t(at 0 3.65 0)
\t\t\t(layer "F.Fab")
\t\t\t${EFFECTS}
\t\t)
\t\t(property "Datasheet" ""
\t\t\t(at 0 0 0)
\t\t\t(layer "F.Fab")
\t\t\t(hide yes)
\t\t\t${EFFECTS}
\t\t)
\t\t(property "Description" "${DESCR}"
\t\t\t(at 0 0 0)
\t\t\t(layer "F.Fab")
\t\t\t(hide yes)
\t\t\t${EFFECTS}
\t\t)
\t\t(fp_circle
\t\t\t(center 0 0)
\t\t\t(end 2.7 0)
\t\t\t(stroke
\t\t\t\t(width 0.15)
\t\t\t\t(type solid)
\t\t\t)
\t\t\t(fill no)
\t\t\t(layer "Cmts.User")
\t\t)
\t\t(fp_circle
\t\t\t(center 0 0)
\t\t\t(end 2.95 0)
\t\t\t(stroke
\t\t\t\t(width 0.05)
\t\t\t\t(type solid)
\t\t\t)
\t\t\t(fill no)
\t\t\t(layer "F.CrtYd")
\t\t)
\t\t(fp_text user "\${REFERENCE}"
\t\t\t(at 0 0 0)
\t\t\t(layer "F.Fab")
\t\t\t${EFFECTS}
\t\t)
\t\t(pad "" np_thru_hole circle
\t\t\t(at 0 0)
\t\t\t(size 2.7 2.7)
\t\t\t(drill 2.7)
\t\t\t(layers "*.Cu" "*.Mask")${padUuid}
\t\t)
\t\t(embedded_fonts no)
\t)`;
}

/**
 * Replace every MountingHole footprint block with the library definition.
 *
 * Returns the new text and how many blocks were rewritten. Idempotent: a block
 * already in library form is detected and left alone.
 */
export function normalizeMountingHoles(text) {
  const marker = `(footprint "${PREFIX}`;
  let out = "";
  let i = 0;
  let rewritten = 0;

  while (i < text.length) {
    const ch = text[i];

    if (ch === '"') {
      const start = i;
      i = skipString(text, i);
      out += text.slice(start, i);
      continue;
    }

    if (text.startsWith(marker, i)) {
      const end = blockEnd(text, i);
      const block = text.slice(i, end);
      const ref = scalar(block, /\(property\s+"Reference"\s+"([^"]+)"/);
      const at = scalar(block, /\(at\s+([-\d.]+ [-\d.]+(?:\s+[-\d.]+)?)\)/);

      if (ref && at && !block.includes('(layer "F.CrtYd")')) {
        rewritten += 1;
        out += libraryBlock({
          ref,
          at,
          fpUuid: scalar(block, /\(uuid\s+"([^"]+)"\)/),
          refUuid: propertyUuid(block, "Reference"),
          padUuid: scalar(block, /\(pad[\s\S]*?\(uuid\s+"([^"]+)"\)/),
        });
        i = end;
        continue;
      }

      out += block;
      i = end;
      continue;
    }

    out += ch;
    i += 1;
  }

  return { text: out, rewritten };
}

function skipString(text, start) {
  let i = start + 1;
  while (i < text.length) {
    if (text[i] === "\\") i += 2;
    else if (text[i] === '"') return i + 1;
    else i += 1;
  }
  return text.length;
}

function blockEnd(text, start) {
  let depth = 0;
  let i = start;
  while (i < text.length) {
    const ch = text[i];
    if (ch === '"') {
      i = skipString(text, i);
      continue;
    }
    if (ch === "(") depth += 1;
    else if (ch === ")") {
      depth -= 1;
      if (depth === 0) return i + 1;
    }
    i += 1;
  }
  return text.length;
}

function main() {
  const board = process.argv[2] ?? DEFAULT_BOARD;
  if (!existsSync(board)) {
    throw new Error(`no board at ${board}`);
  }

  const raw = readFileSync(board, "utf8");
  const newline = raw.includes("\r\n") ? "\r\n" : "\n";
  const { text, rewritten } = normalizeMountingHoles(raw.replace(/\r\n/g, "\n"));

  if (!rewritten) {
    console.log(`${board}: mounting holes already match MountingHole.pretty`);
    return;
  }

  const tmp = `${board}.mcp-tmp`;
  try {
    writeFileSync(tmp, text.replace(/\n/g, newline), "utf8");
    renameSync(tmp, board);
  } catch (err) {
    try {
      unlinkSync(tmp);
    } catch {
      /* nothing to clean up */
    }
    throw err;
  }

  console.log(`${board}`);
  console.log(`  restored ${rewritten} mounting hole(s) to the library definition`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
